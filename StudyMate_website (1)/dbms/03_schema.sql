-- =====================================================================
-- StudyMate AI: database schema (PostgreSQL 15+)
-- The 19 BCNF tables from dbms/01_normalization.md.
--
-- Run:  psql -d studymate -f dbms/03_schema.sql
-- Re-runnable: it drops and recreates the "studymate" schema.
-- =====================================================================
DROP SCHEMA IF EXISTS studymate CASCADE;
CREATE SCHEMA studymate;
SET search_path TO studymate;

-- ---------------------------------------------------------------------
-- People and places
-- ---------------------------------------------------------------------
CREATE TABLE colleges (
    college_id    integer       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    college_name  varchar(150)  NOT NULL,
    city          varchar(60)   NOT NULL,
    UNIQUE (college_name, city)                       -- same name may exist in two cities
);

CREATE TABLE users (
    user_id        integer       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username       varchar(30)   NOT NULL UNIQUE,
    email          varchar(254)  NOT NULL UNIQUE,
    full_name      varchar(100)  NOT NULL,
    password_hash  text          NOT NULL,             -- never store the plain password
    college_id     integer       REFERENCES colleges (college_id) ON DELETE SET NULL,
    created_at     timestamptz   NOT NULL DEFAULT now(),

    CONSTRAINT chk_users_username CHECK (username ~ '^[a-z0-9_]{3,30}$'),
    CONSTRAINT chk_users_email    CHECK (email ~ '^[^@\s]+@[^@\s]+\.[a-z]{2,}$')   -- stored in lower case
);

-- ---------------------------------------------------------------------
-- What is studied
-- ---------------------------------------------------------------------
CREATE TABLE subjects (
    subject_id    smallint     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_name  varchar(50)  NOT NULL UNIQUE
);

CREATE TABLE topics (
    topic_id    integer       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_id  smallint      NOT NULL REFERENCES subjects (subject_id) ON DELETE CASCADE,
    topic_name  varchar(100)  NOT NULL,
    UNIQUE (subject_id, topic_name)                   -- "Kinematics" once per subject
);

-- ---------------------------------------------------------------------
-- Chess-style ratings and titles
-- ---------------------------------------------------------------------
CREATE TABLE titles (
    title_code  varchar(4)   PRIMARY KEY,
    title_name  varchar(30)  NOT NULL UNIQUE,
    min_rating  smallint     NOT NULL UNIQUE CHECK (min_rating >= 0)
);

