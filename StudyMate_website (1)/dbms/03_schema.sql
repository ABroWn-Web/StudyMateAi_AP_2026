CREATE TABLE user_ratings (
    user_id     integer      NOT NULL REFERENCES users (user_id) ON DELETE CASCADE,
    subject_id  smallint     NOT NULL REFERENCES subjects (subject_id) ON DELETE CASCADE,
    rating      smallint     NOT NULL DEFAULT 1200,  -- every new player starts at 1200
    updated_at  timestamptz  NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, subject_id),
    CONSTRAINT chk_ratings_range CHECK (rating BETWEEN 100 AND 3500)
);

-- ---------------------------------------------------------------------
-- Questions: every question is an "opponent" with its own Elo rating
-- ---------------------------------------------------------------------
CREATE TABLE questions (
    question_id      integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    topic_id         integer      NOT NULL REFERENCES topics (topic_id) ON DELETE RESTRICT,
    question_text    text         NOT NULL,
    question_rating  smallint     NOT NULL DEFAULT 1200,
    source           varchar(10)  NOT NULL,
    created_by       integer      REFERENCES users (user_id) ON DELETE SET NULL,   -- NULL for AI-made
    created_at       timestamptz  NOT NULL DEFAULT now(),

    CONSTRAINT chk_questions_text   CHECK (length(btrim(question_text)) > 0),
    CONSTRAINT chk_questions_rating CHECK (question_rating BETWEEN 100 AND 3500),
    CONSTRAINT chk_questions_source CHECK (source IN ('AI', 'TEACHER', 'STUDENT'))
);

CREATE TABLE question_options (
    question_id  integer       NOT NULL REFERENCES questions (question_id) ON DELETE CASCADE,
    option_no    smallint      NOT NULL,
    option_text  varchar(300)  NOT NULL,
    is_correct   boolean       NOT NULL DEFAULT false,
    PRIMARY KEY (question_id, option_no),
    CONSTRAINT chk_options_no CHECK (option_no BETWEEN 1 AND 6),
    -- at most ONE correct option per question
    CONSTRAINT one_correct_option EXCLUDE USING btree (question_id WITH =) WHERE (is_correct)
);

-- ---------------------------------------------------------------------
-- Quizzes and attempts (practice or duel)
-- ---------------------------------------------------------------------
CREATE TABLE quizzes (
    quiz_id          integer       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title            varchar(150)  NOT NULL,
    subject_id       smallint      NOT NULL REFERENCES subjects (subject_id) ON DELETE RESTRICT,
    is_ai_generated  boolean       NOT NULL DEFAULT false,
    created_by       integer       REFERENCES users (user_id) ON DELETE SET NULL,
    created_at       timestamptz   NOT NULL DEFAULT now()
);

CREATE TABLE quiz_questions (
    quiz_id      integer   NOT NULL REFERENCES quizzes (quiz_id) ON DELETE CASCADE,
    position     smallint  NOT NULL,                  -- the "move number"
    question_id  integer   NOT NULL REFERENCES questions (question_id) ON DELETE RESTRICT,
    PRIMARY KEY (quiz_id, position),
    UNIQUE (quiz_id, question_id),                    -- a question appears once per quiz
    CONSTRAINT chk_quiz_questions_position CHECK (position >= 1)
);

CREATE TABLE quiz_attempts (
    attempt_id   bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quiz_id      integer      NOT NULL REFERENCES quizzes (quiz_id) ON DELETE RESTRICT,
    user_id      integer      NOT NULL REFERENCES users (user_id) ON DELETE RESTRICT,  -- keeps duel history intact
    started_at   timestamptz  NOT NULL DEFAULT now(),
    finished_at  timestamptz,                         -- NULL while still playing
    CONSTRAINT chk_attempts_time CHECK (finished_at IS NULL OR finished_at >= started_at)
);

CREATE TABLE attempt_answers (
    attempt_id        bigint    NOT NULL REFERENCES quiz_attempts (attempt_id) ON DELETE CASCADE,
    question_id       integer   NOT NULL REFERENCES questions (question_id) ON DELETE RESTRICT,
    chosen_option_no  smallint,                       -- NULL = skipped / ran out of time
    time_taken_ms     integer   NOT NULL,
    PRIMARY KEY (attempt_id, question_id),
    -- the chosen option must be an option OF THIS question
    FOREIGN KEY (question_id, chosen_option_no) REFERENCES question_options (question_id, option_no),
    CONSTRAINT chk_answers_time CHECK (time_taken_ms >= 0)
);

-- ---------------------------------------------------------------------
-- Duels: two attempts at the same quiz, on a chess clock
-- ---------------------------------------------------------------------
CREATE TABLE duels (
    duel_id            integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    base_seconds       smallint     NOT NULL,         -- Blitz 3+2 -> 180
    increment_seconds  smallint     NOT NULL DEFAULT 0,  --        -> 2 (added after each answer)
    result             varchar(7),                    -- NULL while the duel is running
    termination        varchar(10),
    started_at         timestamptz  NOT NULL DEFAULT now(),
    ended_at           timestamptz,

    CONSTRAINT chk_duels_clock       CHECK (base_seconds BETWEEN 30 AND 3600 AND increment_seconds BETWEEN 0 AND 60),
    CONSTRAINT chk_duels_result      CHECK (result IN ('1-0', '0-1', '1/2-1/2')),
    CONSTRAINT chk_duels_termination CHECK (termination IN ('SCORE', 'RESIGN', 'TIMEOUT', 'ABANDON')),
    -- a finished duel has a result, a reason and an end time; a running one has none of them
    CONSTRAINT chk_duels_finished    CHECK ((result IS NULL) = (termination IS NULL)
                                            AND (result IS NULL) = (ended_at IS NULL)),
    CONSTRAINT chk_duels_time        CHECK (ended_at IS NULL OR ended_at >= started_at)
);

CREATE TABLE duel_players (
    duel_id        integer     NOT NULL REFERENCES duels (duel_id) ON DELETE CASCADE,
    color          varchar(5)  NOT NULL,
    attempt_id     bigint      NOT NULL UNIQUE REFERENCES quiz_attempts (attempt_id) ON DELETE RESTRICT,
    rating_before  smallint    NOT NULL,              -- history: rating at the start of THIS duel
    rating_change  smallint,                          -- NULL until the duel ends
    PRIMARY KEY (duel_id, color),                     -- one White and one Black per duel
    CONSTRAINT chk_players_color  CHECK (color IN ('WHITE', 'BLACK')),
    CONSTRAINT chk_players_rating CHECK (rating_before BETWEEN 100 AND 3500),
    CONSTRAINT chk_players_change CHECK (rating_change BETWEEN -100 AND 100)
);

-- ---------------------------------------------------------------------
-- Focus sessions with chess-puzzle breaks
-- ---------------------------------------------------------------------
CREATE TABLE chess_puzzles (
    puzzle_id       integer       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fen             varchar(100)  NOT NULL UNIQUE,    -- board position in FEN notation
    solution_moves  varchar(200)  NOT NULL,           -- UCI moves, e.g. 'd1d8'
    puzzle_rating   smallint      NOT NULL,
    theme           varchar(40)   NOT NULL,

    CONSTRAINT chk_puzzles_fen      CHECK (fen ~ '^([pnbrqkPNBRQK1-8]{1,8}/){7}[pnbrqkPNBRQK1-8]{1,8} [wb] (-|[KQkq]{1,4}) (-|[a-h][36]) [0-9]+ [0-9]+$'),
    CONSTRAINT chk_puzzles_solution CHECK (solution_moves ~ '^[a-h][1-8][a-h][1-8][qrbn]?( [a-h][1-8][a-h][1-8][qrbn]?)*$'),
    CONSTRAINT chk_puzzles_rating   CHECK (puzzle_rating BETWEEN 100 AND 3500)
);

CREATE TABLE study_sessions (
    session_id       bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          integer      NOT NULL REFERENCES users (user_id) ON DELETE CASCADE,
    subject_id       smallint     NOT NULL REFERENCES subjects (subject_id) ON DELETE RESTRICT,
    started_at       timestamptz  NOT NULL DEFAULT now(),
    ended_at         timestamptz,                     -- NULL while the timer runs
    planned_minutes  smallint     NOT NULL,           -- Pomodoro length
    puzzle_id        integer      REFERENCES chess_puzzles (puzzle_id) ON DELETE RESTRICT,  -- break puzzle
    puzzle_solved    boolean,

    CONSTRAINT chk_sessions_minutes CHECK (planned_minutes IN (25, 50)),
    CONSTRAINT chk_sessions_time    CHECK (ended_at IS NULL OR ended_at > started_at),
    CONSTRAINT chk_sessions_puzzle  CHECK (puzzle_solved IS NULL OR puzzle_id IS NOT NULL)  -- can't solve "no puzzle"
);

-- ---------------------------------------------------------------------
-- AI Mistake Notebook (spaced repetition with Leitner boxes)
-- ---------------------------------------------------------------------
CREATE TABLE mistake_notebook (
    user_id         integer      NOT NULL REFERENCES users (user_id) ON DELETE CASCADE,
    question_id     integer      NOT NULL REFERENCES questions (question_id) ON DELETE CASCADE,
    ai_explanation  text         NOT NULL,            -- written by the AI for THIS student's mistake
    leitner_box     smallint     NOT NULL DEFAULT 1,  -- 1 = review tomorrow ... 5 = review in a month
    next_review_on  date         NOT NULL,
    added_at        timestamptz  NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, question_id),
    CONSTRAINT chk_notebook_box CHECK (leitner_box BETWEEN 1 AND 5)
);

-- ---------------------------------------------------------------------
-- Coaches (BCNF split: coach -> subject lives in "coaches")
-- ---------------------------------------------------------------------
CREATE TABLE coaches (
    coach_id    integer   PRIMARY KEY REFERENCES users (user_id) ON DELETE CASCADE,
    subject_id  smallint  NOT NULL REFERENCES subjects (subject_id) ON DELETE RESTRICT
);

CREATE TABLE coaching (
    student_id  integer  NOT NULL REFERENCES users (user_id) ON DELETE CASCADE,
    coach_id    integer  NOT NULL REFERENCES coaches (coach_id) ON DELETE CASCADE,
    PRIMARY KEY (student_id, coach_id),
    CONSTRAINT chk_coaching_not_self CHECK (student_id <> coach_id)
);

-- The BCNF split lost the rule "one coach per subject per student"
-- (student_id, subject_id -> coach_id). A trigger enforces it instead.
CREATE FUNCTION one_coach_per_subject() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF EXISTS (SELECT 1
               FROM coaching c
               JOIN coaches  existing ON existing.coach_id = c.coach_id
               JOIN coaches  new_c    ON new_c.coach_id    = NEW.coach_id
               WHERE c.student_id = NEW.student_id
                 AND c.coach_id  <> NEW.coach_id
                 AND existing.subject_id = new_c.subject_id) THEN
        RAISE EXCEPTION 'student % already has a coach for this subject', NEW.student_id;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_one_coach_per_subject
    BEFORE INSERT OR UPDATE ON coaching
    FOR EACH ROW EXECUTE FUNCTION one_coach_per_subject();
